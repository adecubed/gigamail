  // lingua corrente (default it)
  let currentLang = 'it';
  try { currentLang = localStorage.getItem('ade_lang') || 'it'; } catch (e) {}

  // traduzione di una chiave nella lingua attiva (fallback: italiano, poi chiave)
  function t(key, fallback) {
    if (!key) return '';
    const L = DICT[currentLang] || DICT.it;
    // fallback: lingua attiva → inglese → italiano → chiave (cosi' una
    // traduzione parziale, es. il cinese appena nato, degrada con grazia).
    // A key in no dictionary returns the caller's own text, when it gives
    // one, rather than the bare key name.
    return L[key] || DICT.en[key] || DICT.it[key] || fallback || key;
  }

  // applica la lingua a tutto il DOM (elementi con data-i18n*)
  function applyLang(lang) {
    if (lang) currentLang = lang;
    try { localStorage.setItem('ade_lang', currentLang); } catch (e) {}

    // testo interno
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (val && val !== key) el.textContent = val;   // unknown key: keep the markup's text
    });
    // placeholder
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.getAttribute('data-i18n-ph');
      const val = t(key);
      if (val && val !== key) el.setAttribute('placeholder', val);
    });
    // title (tooltip)
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = t(key);
      if (val && val !== key) el.setAttribute('title', val);
    });
    // markup from the dictionary itself (static text with <code>, never user
    // data): the element keeps its formatting
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const val = t(key);
      if (val && val !== key) el.innerHTML = val;
    });
    // data-label (voci sidebar: tooltip via attributo data-label)
    document.querySelectorAll('[data-i18n-label]').forEach(el => {
      const key = el.getAttribute('data-i18n-label');
      const val = t(key);
      if (val && val !== key) el.setAttribute('data-label', val);
    });
    // attributo lang sul documento + bottone lingua (sigla attiva)
    document.documentElement.setAttribute('lang', currentLang);
    const flag = document.getElementById('langSwitch');
    if (flag) flag.textContent =
      currentLang === 'it' ? 'IT' : currentLang === 'zh' ? '中' : 'EN';
    // The main process shows menus, notifications and dialogs by itself: tell
    // it the language (only the main window's preload offers setLang).
    try {
      if (window.electronAPI && window.electronAPI.setLang) window.electronAPI.setLang(currentLang);
    } catch (e) { /* a page without the bridge keeps the main process as it is */ }
  }

  function toggleLang() {
    const order = { it: 'en', en: 'zh', zh: 'it' };
    applyLang(order[currentLang] || 'it');
    // refresh viste dinamiche (liste/card generate da JS) se le funzioni esistono
    try {
      if (typeof window.refreshCurrentFolder === 'function') window.refreshCurrentFolder();
      if (typeof window.loadAccounts === 'function') window.loadAccounts();
    } catch (e) {}
  }

  // espone API globale
  // Locale per Intl (date, ore, nomi di mesi e giorni): segue la lingua
  // della UI, non quella del sistema. Prima era 'it-IT' fisso ovunque.
  const LOCALES = { it: 'it-IT', en: 'en-GB', zh: 'zh-CN' };
  window.i18n = {
    t, applyLang, toggleLang,
    // read-only list of a language's keys, for the dictionary tests
    keys: (lang) => Object.keys(DICT[lang] || {}),
    get lang() { return currentLang; },
    get locale() { return LOCALES[currentLang] || 'it-IT'; },
  };

  // applica al caricamento
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyLang());
  } else {
    applyLang();
  }
