"""Genera la sezione tool di MAPPA_MCP.md dal server reale (fonte di verita'
unica: mcp.list_tools). Uso:

    python -m gigamail.gen_toolmap          # riscrive la sezione
    python -m gigamail.gen_toolmap --check  # exit 1 se divergente (CI)

La classe di rischio e' derivata dal server stesso: DANGEROUS = il tool ha il
request_id fuori banda (due fasi); WRITE_SAFE = azioni reversibili note;
il resto e' READ.
"""
import asyncio
import sys
from pathlib import Path

# The map is in English first, then Italian: one generated box per language.
MARKERS = {
    "en": ("<!-- TOOLMAP:BEGIN (generated by gen_toolmap — do not edit by hand) -->",
           "<!-- TOOLMAP:END -->"),
    "it": ("<!-- TOOLMAP-IT:BEGIN (generated by gen_toolmap — do not edit by hand) -->",
           "<!-- TOOLMAP-IT:END -->"),
}
HEADINGS = {
    "en": ("## Exposed tools ({n} — generated from the server)", "two-phase"),
    "it": ("## Riepilogo tool esposti ({n} — generato dal server)", "due fasi"),
}

WRITE_SAFE_TOOLS = {"mark_read", "create_folder"}


def _mappa_path() -> Path:
    return Path(__file__).resolve().parent.parent.parent / "MAPPA_MCP.md"


def _classify(tool) -> str:
    props = (tool.input_schema or {}).get("properties", {})
    if "request_id" in props:
        return "DANGEROUS"
    if tool.name in WRITE_SAFE_TOOLS:
        return "WRITE_SAFE"
    return "READ"


def generate(lang: str = "en") -> str:
    from gigamail.server import mcp
    tools = asyncio.new_event_loop().run_until_complete(mcp.list_tools())
    by_class = {"READ": [], "WRITE_SAFE": [], "DANGEROUS": []}
    for t in tools:
        by_class[_classify(t)].append(t.name)
    heading, two_phase = HEADINGS[lang]
    lines = [heading.format(n=len(tools)), ""]
    lines.append(f"**READ ({len(by_class['READ'])}):** "
                 + ", ".join(f"`{n}`" for n in by_class["READ"]))
    lines.append(f"**WRITE_SAFE ({len(by_class['WRITE_SAFE'])}):** "
                 + ", ".join(f"`{n}`" for n in by_class["WRITE_SAFE"]))
    lines.append(f"**DANGEROUS ({len(by_class['DANGEROUS'])}, {two_phase}):** "
                 + ", ".join(f"`{n}`" for n in by_class["DANGEROUS"]))
    return "\n".join(lines)


def render(current: str) -> str:
    for lang, (begin, end) in MARKERS.items():
        if begin not in current or end not in current:
            raise SystemExit(f"Markers {begin!r} not found in MAPPA_MCP.md")
        block = f"{begin}\n{generate(lang)}\n{end}"
        pre = current.split(begin)[0]
        post = current.split(end)[1]
        current = pre + block + post
    return current


def main() -> int:
    path = _mappa_path()
    current = path.read_text(encoding="utf-8")
    updated = render(current)
    if "--check" in sys.argv:
        if updated != current:
            print("MAPPA_MCP.md NON allineata ai tool del server: "
                  "rigenera con python -m gigamail.gen_toolmap")
            return 1
        print("MAPPA_MCP.md allineata al server.")
        return 0
    path.write_text(updated, encoding="utf-8", newline="")
    print(f"Sezione tool rigenerata in {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
